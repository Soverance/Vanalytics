// src/Vanalytics.Web/scripts/gen-action-catalogs.mjs
// Regenerate the WS/JA/buffs catalogs from Windower Resources. Usage (from src/Vanalytics.Web, in Docker):
//   1) copy res files in:  cp "F:/Final Fantasy XI/Windower4/res/weapon_skills.lua" scripts/_weapon_skills.lua
//                          cp "F:/Final Fantasy XI/Windower4/res/job_abilities.lua" scripts/_job_abilities.lua
//                          cp "F:/Final Fantasy XI/Windower4/res/buffs.lua" scripts/_buffs.lua
//   2) node scripts/gen-action-catalogs.mjs
//   3) delete scripts/_*.lua (do not commit them)
import { readFileSync, writeFileSync } from 'node:fs'

const ucfirst = (s) => s.charAt(0).toUpperCase() + s.slice(1)
const titleCase = (s) => s.split(' ').map(ucfirst).join(' ')

// buffs.lua has no prefix= field; match id= + en=, skip empty/duplicate en.
function parseBuffs(path) {
  const rows = []
  const seen = new Set()
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const id = line.match(/\bid=(\d+)/)?.[1]
    const en = line.match(/\ben="((?:[^"\\]|\\.)*)"/)?.[1]
    if (!id || !en || en.length === 0) continue
    if (seen.has(en)) continue          // keep first (lowest id) per name
    seen.add(en)
    rows.push({ id: Number(id), name: en, label: titleCase(en) })
  }
  rows.sort((a, b) => a.label.localeCompare(b.label))
  return rows
}

function parse(path, prefix) {
  const rows = []
  const seen = new Set()
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    if (!line.includes(`prefix="${prefix}"`)) continue
    const id = line.match(/\bid=(\d+)/)?.[1]
    const en = line.match(/\ben="((?:[^"\\]|\\.)*)"/)?.[1]
    if (!id || !en || en.length === 0) continue
    if (seen.has(en)) continue
    seen.add(en)
    const skill = line.match(/\bskill=(\d+)/)?.[1]
    rows.push({ id: Number(id), name: en, skill: skill ? Number(skill) : undefined })
  }
  rows.sort((a, b) => a.name.localeCompare(b.name))
  return rows
}

function emit(rows, withSkill) {
  return rows.map(r =>
    withSkill
      ? `    { id: ${r.id}, name: ${JSON.stringify(r.name)}, skill: ${r.skill ?? 0} },`
      : `    { id: ${r.id}, name: ${JSON.stringify(r.name)} },`).join('\n')
}

const ws = parse('scripts/_weapon_skills.lua', '/weaponskill')
const ja = parse('scripts/_job_abilities.lua', '/jobability')

writeFileSync('src/lib/weaponSkills.ts',
`// Weapon-skill catalog for the GearSwap workflow editor's action picker.
// Source: Windower Resources weapon_skills.lua (prefix="/weaponskill" only).
// Generated by scripts/gen-action-catalogs.mjs — regenerate when Windower updates.

export interface WeaponSkillEntry { id: number; name: string; skill: number }

export const WEAPON_SKILLS: WeaponSkillEntry[] = [
${emit(ws, true)}
]
`)

writeFileSync('src/lib/jobAbilities.ts',
`// Job-ability catalog for the GearSwap workflow editor's action picker.
// Source: Windower Resources job_abilities.lua (prefix="/jobability" only).
// No job/level: Windower's data carries no ability->job mapping (per-job filtering deferred).
// Generated by scripts/gen-action-catalogs.mjs — regenerate when Windower updates.

export interface JobAbilityEntry { id: number; name: string }

export const JOB_ABILITIES: JobAbilityEntry[] = [
${emit(ja, false)}
]
`)

const buffs = parseBuffs('scripts/_buffs.lua')
const buffsRows = buffs.map(b => `    { id: ${b.id}, name: ${JSON.stringify(b.name)}, label: ${JSON.stringify(b.label)} },`).join('\n')
writeFileSync('src/lib/buffs.ts',
`// Buff catalog for the GearSwap workflow editor's buff_change picker.
// Source: Windower Resources buffs.lua (all status effects).
// 'name' is the RAW en verbatim — GearSwap's buff_change(buff,gain) compares res.buffs[id].name,
// which resolves to the raw en (no capitalization). Casing is inconsistent by source
// ("Sneak Attack" Title, "doom" lowercase) — do not transform it or branches never fire.
// 'label' is a Title-Case display-only form. Generated by scripts/gen-action-catalogs.mjs.

export interface BuffEntry { id: number; name: string; label: string }

export const BUFFS: BuffEntry[] = [
${buffsRows}
]
`)

console.log(`weaponSkills: ${ws.length}, jobAbilities: ${ja.length}, buffs: ${buffs.length}`)
